#ifndef DRV_WK2132_I2C2_H
#define DRV_WK2132_I2C2_H

/* Concrete I2C2 backend for the portable wk2132 service (Task 5).
 *
 * DFR0627 (WK2132 dual UART-over-I2C bridge) on I2C2 (PA11 SCL / PB14 SDA).
 * Implements wk2132_i2c_t as raw I2C2 transport: mem_read/mem_write move
 * `len` bytes at register `reg` (SPAGE/SCR/LCR/FCR/... register access);
 * tx/rx move `len` raw bytes with no register pointer (the WK2132 FIFO
 * object address). All WK2132 register semantics live in the portable
 * App/services/wk2132.c, not here. This driver only shifts the 7-bit
 * device address the caller computes into the 8-bit form HAL expects.
 *
 * NOTE: hi2c2 does not exist yet -- it is generated by the CubeMX I2C2
 * enable step (PA11=I2C2_SCL, PB14=I2C2_SDA, open-drain, 100 kHz), which
 * is a user-driven GUI step (see docs/vevor-heater.md, Task 7). This
 * driver assumes that step has been applied and MX_I2C2_Init() has run.
 *
 * Bench bring-up plan Task 7:
 *   .superpowers/sdd/2026-09-03-vevor-heater-firmware/task-7-brief.md
 */
#include "wk2132.h"

/* Factory: hand this to heater_init(). */
const wk2132_i2c_t *drv_wk2132_i2c2_backend(void);

#endif /* DRV_WK2132_I2C2_H */
